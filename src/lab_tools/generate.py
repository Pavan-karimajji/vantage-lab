"""Generator (LAB-15, LAB-16).

``python -m lab_tools.generate --topology catalogue/<name>.yaml --out <dir>`` writes, per
component, under ``<dir>/<topology>/<component>/``: ``src/component/<component>_ports.hpp``,
``ports.yaml``, ``lab_params.hpp``, ``lab_component.hpp``, ``lab_sil.cpp`` and ``default.yaml``.
It writes no value of its own into C++ except names and the memory flag; every
threshold is a calibration key of ``default.yaml``. Standard library and PyYAML only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import string
import sys
from pathlib import Path
from typing import Any, Mapping

import yaml

from lab_tools.setup_writer import ProvisionalError, load_provisional  # noqa: F401  (the one reader of provisional.yaml)
from lab_tools.topology import IMAGE_KIND, ComponentDesc, Topology, TopologyError, load_topology

TEMPLATE_DIR = Path(__file__).resolve().parents[2] / "template"
PROVISIONAL_FILE = "provisional.yaml"

# Message types of the ports (RCT_Architecture.md section 0; D20 for the lab payload).
CONTROL_TYPE = "adas.common.CycleControl"
SAMPLE_TYPE = "adas.lab.LabSample"
REF_SYNC_TYPE = "adas.common.RefSync"
COMP_STATE_TYPE = "adas.df.CompState"

_IDENTIFIER = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
_SOURCE_FILES = ("src/component/{component}_ports.hpp", "ports.yaml", "lab_params.hpp", "lab_component.hpp",
                 "lab_sil.cpp")


class GenerateError(Exception):
    """The generator cannot write a component; the message names the component (and the key)."""


# ---- names the generator derives --------------------------------------------------------------

def calibration_key(component: str, name: str) -> str:
    """``LAB_<COMPONENT>_<NAME>_<UNIT>`` (R-NAME-3)."""
    return f"LAB_{component.upper()}_{name}"


def provisional_keys(component: str) -> tuple[str, str]:
    return calibration_key(component, "MAX_AGE_US"), calibration_key(component, "RECOVERY_RUNS")


def switch_keys(component: str) -> tuple[str, str]:
    return calibration_key(component, "HANG_AFTER_RUNS"), calibration_key(component, "CRASH_AFTER_RUNS")


def input_port_names(comp: ComponentDesc) -> list[str]:
    """Manifest data inputs, in declared order (the only order, RCT:IMP-0028)."""
    return [i.name for i in comp.inputs]


def manifest_input_names(comp: ComponentDesc) -> list[str]:
    return ["control"] + input_port_names(comp)


def manifest_output_names(comp: ComponentDesc) -> list[str]:
    return list(comp.outputs) + ["refSync", "compState"]


def ref_sync_entries(comp: ComponentDesc) -> list[str]:
    """The refSync entries, in order: the data inputs only, never ``control``."""
    return input_port_names(comp)


def library_name(topology: str, component: str) -> str:
    return f"lab_{topology}_{component}"


# ---- the calibration file ---------------------------------------------------------------------

def _provisional_value(provisional: Mapping[str, Any], topology: str, comp: str, key: str) -> int:
    entry = (((provisional.get(topology) or {}).get(comp)) or {}).get(key)
    if entry is None:
        raise GenerateError(f"component {comp} of topology {topology}: calibration key {key} is not given in "
                            f"{PROVISIONAL_FILE} (no default in code)")
    value = entry.get("value") if isinstance(entry, dict) else entry
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise GenerateError(f"component {comp} of topology {topology}: calibration key {key} must be a "
                            f"non-negative integer, got {value!r}")
    return value


def write_default_yaml(path: Path, topology: str, comp: ComponentDesc, provisional: Mapping[str, Any]) -> None:
    """The component's calibration: the two provisional keys and the two ``..._AFTER_RUNS`` at 0."""
    max_age_key, recovery_key = provisional_keys(comp.name)
    hang_key, crash_key = switch_keys(comp.name)
    lines = [
        f"# Generated by lab_tools.generate for {topology}/{comp.name}. Calibration of one lab component (R-NAME-3).",
        f"{max_age_key}: {_provisional_value(provisional, topology, comp.name, max_age_key)}",
        f"{recovery_key}: {_provisional_value(provisional, topology, comp.name, recovery_key)}",
        f"{hang_key}: 0",
        f"{crash_key}: 0",
    ]
    _write(path, "\n".join(lines) + "\n")


# ---- the port files ---------------------------------------------------------------------------

def _input_proto_type(topology: Topology, comp: ComponentDesc, producer: str) -> str:
    source = topology.source(producer)
    if source is not None and source.kind == IMAGE_KIND:
        raise GenerateError(f"component {comp.name} of topology {topology.name}: input from image source "
                            f"{producer} is not supported (a component that consumes the image is parked)")
    return SAMPLE_TYPE


def write_ports_yaml(path: Path, topology: Topology, comp: ComponentDesc) -> None:
    """The port declaration ``adas_generate_sil_ports`` reads: ungated, names, ``proto_type``, ``binds``."""
    lines = [f"# Generated by lab_tools.generate for {topology.name}/{comp.name}. Ungated (R-SIM-22).",
             f"component: {comp.name}", "inputs:"]
    lines.append(f"  - {{name: control, proto_type: {CONTROL_TYPE}, binds: control}}")
    for inp in comp.inputs:
        lines.append(f"  - {{name: {inp.name}, proto_type: {_input_proto_type(topology, comp, inp.producer)}, "
                     f"binds: {inp.name}}}")
    lines.append("outputs:")
    for name in comp.outputs:
        lines.append(f"  - {{name: {name}, proto_type: {SAMPLE_TYPE}, binds: {name}}}")
    lines.append(f"  - {{name: refSync, proto_type: {REF_SYNC_TYPE}, binds: refSync}}")
    lines.append(f"  - {{name: compState, proto_type: {COMP_STATE_TYPE}, binds: compState}}")
    _write(path, "\n".join(lines) + "\n")


def write_ports_header(path: Path, topology: Topology, comp: ComponentDesc) -> None:
    """``src/component/<component>_ports.hpp``: the ports struct ``gen_sil_ports.py`` checks ``binds:`` against."""
    ins = input_port_names(comp)
    outs = list(comp.outputs)
    n_in, n_out = len(ins), len(outs)

    def array_of(items: list[str]) -> str:
        return "{{" + ", ".join(items) + "}}" if items else "{}"

    samples = array_of([f"{n}.valid ? &{n}.data : nullptr" for n in ins])
    malformed = " || ".join(["control.malformed"] + [f"{n}.malformed" for n in ins])
    data_outputs = array_of([f"&{n}.data" for n in outs])
    marks = "".join(f"{n}.updated = true; " for n in outs)
    req_members = "".join(f"  ReqPort<adas::lab::LabSample> {n};\n" for n in ins)
    pro_members = "".join(f"  ProPort<adas::lab::LabSample> {n};\n" for n in outs)
    text = f"""// Copyright (c) LT EPS. All Rights Reserved.
// Proprietary and Confidential.
// COMPONENT: VANTAGE_LAB
/// @file
/// @brief
///   Ports of lab component {comp.name} of topology {topology.name}: control, one member per data
///   input in declared order, the data outputs, refSync and compState. Generated by lab_tools.generate.
/// @author Pavan Karimajji <Pavan.Karimajji@larsentoubro.com>

#pragma once

#include <array>

#include "common/comp_state.pb.h"
#include "common/cycle_control.pb.h"
#include "common/ref_sync.pb.h"
#include "lab/lab_sample.pb.h"

namespace lab {{

template <typename T>
struct ReqPort {{
  T data;
  bool valid = false;
  bool malformed = false;
  double ageS = 0.0;
}};

template <typename T>
struct ProPort {{
  T data;
  bool updated = false;
}};

struct LabReqPorts {{
  ReqPort<adas::common::CycleControl> control;
{req_members}
  /// The samples offered this run in declared order, null for an input not offered.
  std::array<const adas::lab::LabSample*, {n_in}> samples() const {{ return {samples}; }}
  bool anyMalformed() const {{ return {malformed}; }}
}};

struct LabProPorts {{
{pro_members}  ProPort<adas::common::RefSync> refSync;
  ProPort<adas::df::CompState> compState;

  std::array<adas::lab::LabSample*, {n_out}> dataOutputs() {{ return {data_outputs}; }}
  void markUpdated() {{ {marks}refSync.updated = true; compState.updated = true; }}
}};

}}  // namespace lab
"""
    _write(path, text)


def write_params_header(path: Path, topology: Topology, comp: ComponentDesc) -> None:
    """``lab_params.hpp``: the names and the memory flag, nothing else."""
    max_age_key, recovery_key = provisional_keys(comp.name)
    hang_key, crash_key = switch_keys(comp.name)
    ins = input_port_names(comp)
    outs = list(comp.outputs)

    def names(items: list[str]) -> str:
        return "{{" + ", ".join(f'"{n}"' for n in items) + "}}" if items else "{}"

    text = f"""// Copyright (c) LT EPS. All Rights Reserved.
// Proprietary and Confidential.
// COMPONENT: VANTAGE_LAB
/// @file
/// @brief
///   Names and the memory flag of lab component {comp.name} of topology {topology.name}. Generated by
///   lab_tools.generate; no threshold lives here, every value is a calibration key.
/// @author Pavan Karimajji <Pavan.Karimajji@larsentoubro.com>

#pragma once

#include <array>
#include <cstddef>

namespace lab {{

constexpr const char* kComponentName = "{comp.name}";
constexpr std::size_t kInputCount = {len(ins)};
constexpr std::array<const char*, {len(ins)}> kInputNames = {names(ins)};
constexpr std::size_t kOutputCount = {len(outs)};
constexpr std::array<const char*, {len(outs)}> kOutputNames = {names(outs)};
constexpr bool kMemory = {"true" if comp.memory else "false"};
constexpr const char* kMaxAgeKey = "{max_age_key}";
constexpr const char* kRecoveryKey = "{recovery_key}";
constexpr const char* kHangKey = "{hang_key}";
constexpr const char* kCrashKey = "{crash_key}";

}}  // namespace lab
"""
    _write(path, text)


def _fill(template: str, **values: str) -> str:
    return string.Template(template).substitute(values)


def generate_component(topology: Topology, comp: ComponentDesc, out_dir: Path, provisional: Mapping[str, Any],
                       template_dir: Path = TEMPLATE_DIR) -> dict[str, Any]:
    """Write every file of one component; return ``{"dir", "build_id", "files"}``.

    The declared input order is the manifest input order and the ``RefSyncBuilder`` order: the same
    list, ``input_port_names``, feeds ``ports.yaml``, ``<component>_ports.hpp`` and ``lab_params.hpp``.
    """
    for what, name in (("component", comp.name), *[("input", i.name) for i in comp.inputs],
                       *[("output", o) for o in comp.outputs]):
        if not _IDENTIFIER.match(name):
            raise GenerateError(f"component {comp.name} of topology {topology.name}: {what} name {name!r} is not "
                                f"a C++ identifier")
    comp_dir = Path(out_dir) / topology.name / comp.name
    values = dict(component=comp.name, topology=topology.name, library=library_name(topology.name, comp.name))

    write_ports_yaml(comp_dir / "ports.yaml", topology, comp)
    write_ports_header(comp_dir / "src" / "component" / f"{comp.name}_ports.hpp", topology, comp)
    write_params_header(comp_dir / "lab_params.hpp", topology, comp)
    _write(comp_dir / "lab_component.hpp",
           _fill((template_dir / "lab_component.hpp.in").read_text(encoding="utf-8"), **values))
    _write(comp_dir / "lab_sil.cpp", _fill((template_dir / "lab_sil.cpp.in").read_text(encoding="utf-8"), **values))
    write_default_yaml(comp_dir / "default.yaml", topology.name, comp, provisional)

    digest = hashlib.sha256()
    for rel in _SOURCE_FILES:
        rel = rel.format(component=comp.name)
        digest.update(rel.encode("utf-8") + b"\n")
        digest.update((comp_dir / rel).read_bytes())
    return {"dir": comp_dir, "build_id": digest.hexdigest()[:16]}


def write_index(path: Path, topology: str, entries: Mapping[str, Mapping[str, str]]) -> None:
    """``<sil build dir>/lab/<topology>/index.json``: component -> library path, config folder, build id."""
    text = json.dumps({"topology": topology, "components": dict(entries)}, indent=2, sort_keys=True)
    _write(path, text + "\n")


def generate_topology(topology: Topology, out_dir: Path, provisional: Mapping[str, Any], *,
                      lab_dir: Path | None = None, library_prefix: str = "", library_suffix: str = "",
                      template_dir: Path = TEMPLATE_DIR) -> dict[str, dict[str, str]]:
    """Generate every component of ``topology``; write ``index.json``; return the index entries."""
    lab_dir = Path(lab_dir) if lab_dir is not None else Path(out_dir)
    entries: dict[str, dict[str, str]] = {}
    for comp in topology.components:
        info = generate_component(topology, comp, out_dir, provisional, template_dir)
        lib = library_name(topology.name, comp.name)
        folder = lab_dir / topology.name / comp.name
        entries[comp.name] = {
            "library": (folder / f"{library_prefix}{lib}{library_suffix}").as_posix(),
            "config": (folder / "config").as_posix(),
            "build_id": info["build_id"],
        }
    write_index(lab_dir / topology.name / "index.json", topology.name, entries)
    return entries


def _write(path: Path, text: str) -> None:
    """Write ``text`` as UTF-8 with LF; leave an identical file alone, so a re-configure rebuilds nothing."""
    path = Path(path)
    data = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--topology", required=True, type=Path, help="catalogue/<name>.yaml")
    parser.add_argument("--out", required=True, type=Path, help="directory the generated sources go into")
    parser.add_argument("--provisional", type=Path, help=f"default: {PROVISIONAL_FILE} beside the topology file")
    parser.add_argument("--lab-dir", type=Path, help="<sil build dir>/lab; default: --out")
    parser.add_argument("--library-prefix", default="")
    parser.add_argument("--library-suffix", default="")
    args = parser.parse_args(argv)
    try:
        topology = load_topology(args.topology)
        provisional = load_provisional(args.provisional or args.topology.parent / PROVISIONAL_FILE)
        generate_topology(topology, args.out, provisional, lab_dir=args.lab_dir,
                          library_prefix=args.library_prefix, library_suffix=args.library_suffix)
    except (TopologyError, GenerateError, ProvisionalError) as exc:
        print(f"lab_tools.generate: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
